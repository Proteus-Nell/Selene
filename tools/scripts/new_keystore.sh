#!/usr/bin/env bash
#
# Create the release keystore and point the Android build at it.
#
#   usage: tools/scripts/new_keystore.sh <path-to-new-keystore.jks>
#
# Run this once, ever. The key it creates is the app's identity for the rest of
# its life: Android refuses an upgrade signed by a different key, so losing this
# file strands every installed copy, and there is no recovery for a
# self-distributed APK. The keystore is therefore written OUTSIDE the working
# tree, and this script refuses to write it inside one.
#
# What it produces:
#   <path>                     the keystore itself, which you must back up
#   app/android/key.properties gitignored, points the Gradle build at <path>
#
# See docs/RELEASE.md for the rest of the release procedure.

set -euo pipefail

DEST="${1:-}"
if [[ -z "$DEST" ]]; then
  echo "usage: $0 <path-to-new-keystore.jks>" >&2
  echo "       e.g. $0 ~/keys/period-tracker-release.jks" >&2
  exit 2
fi

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PROPS="$REPO_ROOT/app/android/key.properties"

# Resolve the destination without requiring it to exist yet.
DEST_DIR="$(cd "$(dirname "$DEST")" 2>/dev/null && pwd || true)"
if [[ -z "$DEST_DIR" ]]; then
  echo "ERROR: directory for '$DEST' does not exist. Create it first." >&2
  exit 2
fi
DEST_ABS="$DEST_DIR/$(basename "$DEST")"

# A keystore inside the repository is one `git add -A` away from being public,
# and a published signing key cannot be un-published: anyone holding it can ship
# an update that Android will install over the real app.
if [[ "$DEST_ABS" == "$REPO_ROOT"/* ]]; then
  echo "ERROR: refusing to write a keystore inside the repository." >&2
  echo "       Choose a path outside $REPO_ROOT (e.g. ~/keys/)." >&2
  exit 2
fi

if [[ -e "$DEST_ABS" ]]; then
  echo "ERROR: $DEST_ABS already exists. Refusing to overwrite a signing key." >&2
  exit 2
fi
if [[ -e "$PROPS" ]]; then
  echo "ERROR: $PROPS already exists." >&2
  echo "       Remove it deliberately if you really are replacing the key." >&2
  exit 2
fi

if ! command -v keytool >/dev/null 2>&1; then
  echo "ERROR: keytool not found. Install a JDK (21 is what CI uses)." >&2
  exit 2
fi

# Confirm the gitignore actually covers the properties file before writing a
# password into it, rather than trusting that it still does.
if ! git -C "$REPO_ROOT" check-ignore -q "$PROPS"; then
  echo "ERROR: $PROPS is not gitignored. Fix .gitignore before continuing." >&2
  exit 2
fi

read -r -p "Key alias [upload]: " ALIAS
ALIAS="${ALIAS:-upload}"

read -r -s -p "Keystore password: " STORE_PASS; echo
read -r -s -p "Confirm: " STORE_PASS_CONFIRM; echo
if [[ "$STORE_PASS" != "$STORE_PASS_CONFIRM" ]]; then
  echo "ERROR: passwords do not match." >&2
  exit 2
fi
if (( ${#STORE_PASS} < 6 )); then
  echo "ERROR: keytool requires at least 6 characters." >&2
  exit 2
fi

# One password for both store and key. Two would be two things to lose, and the
# threat model here is losing the file, not an attacker who already has it.
keytool -genkeypair \
  -alias "$ALIAS" \
  -keyalg RSA \
  -keysize 4096 \
  -validity 10000 \
  -keystore "$DEST_ABS" \
  -storetype PKCS12 \
  -storepass "$STORE_PASS" \
  -keypass "$STORE_PASS" \
  -dname "CN=Period Tracker, OU=Unknown, O=Unknown, L=Unknown, S=Unknown, C=Unknown"

chmod 600 "$DEST_ABS"

umask 077
cat > "$PROPS" <<EOF
# Gitignored. Generated by tools/scripts/new_keystore.sh.
# storeFile is read by app/android/app/build.gradle.kts.
storePassword=$STORE_PASS
keyPassword=$STORE_PASS
keyAlias=$ALIAS
storeFile=$DEST_ABS
EOF
chmod 600 "$PROPS"

# Belt and braces: if this ever prints something, the write above was a leak.
if ! git -C "$REPO_ROOT" check-ignore -q "$PROPS"; then
  echo "ERROR: $PROPS is tracked. Delete it and fix .gitignore." >&2
  exit 1
fi

cat <<EOF

Keystore written to $DEST_ABS
Properties written to $PROPS (gitignored)

Back the keystore up now, somewhere that is not this machine and not this
repository. If you lose it, no installed copy of the app can ever be upgraded.

Next: bash tools/scripts/release.sh, or see docs/RELEASE.md.
EOF
